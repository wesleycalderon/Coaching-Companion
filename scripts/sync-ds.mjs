// Copies the vendored BTS Studio design system into the places the app loads it from.
//  - public/ds/: tokens.css and bundle.css, linked from the root layout.
//  - src/ds/types.d.ts: the system's component types (components/index.d.ts).
//  - src/ds/bundle.generated.js: bundle.js wrapped in a factory that takes `window` as a
//    parameter, so the real BTSStudio components render on the server and the client alike.
// Edit nothing in public/ds or src/ds/bundle.generated.js by hand: re-run this script.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ds = join(root, 'design-system');

mkdirSync(join(root, 'public/ds/components'), { recursive: true });
copyFileSync(join(ds, 'tokens.css'), join(root, 'public/ds/tokens.css'));
copyFileSync(join(ds, 'components/bundle.css'), join(root, 'public/ds/components/bundle.css'));

const bundle = readFileSync(join(ds, 'components/bundle.js'), 'utf8');
if (!bundle.includes('var BTSStudio =')) {
  throw new Error('design-system/components/bundle.js no longer declares `var BTSStudio`; update scripts/sync-ds.mjs.');
}
const wrapped = `/* Generated by scripts/sync-ds.mjs from design-system/components/bundle.js. Do not edit. */
/* eslint-disable */
export function createBTSStudio(window) {
${bundle}
return BTSStudio;
}
`;
mkdirSync(join(root, 'src/ds'), { recursive: true });
writeFileSync(join(root, 'src/ds/bundle.generated.js'), wrapped);
// Component prop types, from the system's own index.d.ts.
copyFileSync(join(ds, 'components/index.d.ts'), join(root, 'src/ds/types.d.ts'));
console.log('BTS Studio design system synced.');
